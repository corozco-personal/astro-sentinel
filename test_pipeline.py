"""
Unit and simulation tests to validate detection algorithms:
1. Synthetic Gravitational Microlensing curve of a stellar-mass black hole (M ~ 10 M_sun, tE ~ 40 days).
2. Synthetic ellipsoidal modulation curve generated by a compact object.
3. Validation against the official SIMBAD cross-match module.
"""
import numpy as np
import lightkurve as lk
from astropy.time import Time
from pipeline.detectors.microlensing import MicrolensingDetector, paczynski_model
from pipeline.detectors.ellipsoidal import EllipsoidalDetector
from pipeline.cross_match import CatalogCrossMatcher

def test_microlensing_synthetic():
    print("\n--- Test 1: Microlensing Event Simulation (Isolated Black Hole) ---")
    time_arr = np.linspace(1500, 1580, 1500)
    # Typical astrophysical parameters for a massive lens
    true_t0 = 1540.0
    true_u0 = 0.25
    true_tE = 35.0  # Einstein radius crossing time characteristic of BH
    true_fbase = 1.0

    clean_flux = paczynski_model(time_arr, true_t0, true_u0, true_tE, true_fbase)
    # Realistic TESS photometric noise (~200 ppm)
    noise = np.random.normal(0, 0.005, size=len(time_arr))
    flux_with_noise = clean_flux + noise

    lc = lk.LightCurve(time=Time(time_arr, format='btjd'), flux=flux_with_noise, flux_err=np.full_like(flux_with_noise, 0.005))
    detector = MicrolensingDetector()
    res = detector.evaluate(lc)

    print("Microlensing result:", res)
    assert res["is_candidate"] is True, "Detector should identify the BH microlensing event"
    print(f"-> Successfully detected: t0={res['t0']:.2f}, u0={res['u0']:.3f}, tE={res['tE_days']:.1f} days, delta_chi2={res['delta_chi2']:.1f}")

def test_ellipsoidal_synthetic():
    print("\n--- Test 2: Ellipsoidal Modulation Simulation (Binary with Dark Companion) ---")
    time_arr = np.linspace(1500, 1550, 1000)
    orbital_period = 4.2  # days
    omega = 2 * np.pi / orbital_period

    # Harmonic modulation with main component at 2*f_orb (tidal / ellipsoidal effect)
    flux_clean = 1.0 + 0.015 * np.cos(2 * omega * time_arr) + 0.004 * np.cos(omega * time_arr)
    noise = np.random.normal(0, 0.001, size=len(time_arr))
    flux_noisy = flux_clean + noise

    lc = lk.LightCurve(time=Time(time_arr, format='btjd'), flux=flux_noisy)
    detector = EllipsoidalDetector()
    # Realistic red giant star parameters (massive companion induces strong tide)
    res = detector.evaluate(lc, star_mass=1.5, star_rad=3.0)

    print("Ellipsoidal result:", res)
    assert res["is_candidate"] is True, "Detector should identify the ellipsoidal tidal modulation"
    print(f"-> Successfully detected: Period={res['detected_period_days']:.2f} d, SNR={res['snr']:.1f}")

def test_cross_match_mock():
    print("\n--- Test 3: Verification against official sources ---")
    matcher = CatalogCrossMatcher()

    # Known black hole in the literature (Cygnus X-1)
    res_bh = matcher.check_simbad_and_mast("Cyg X-1")
    print("Cross-match Cyg X-1:", res_bh)
    assert res_bh["is_documented_black_hole"] is True, "Cyg X-1 must be detected as a known black hole"

    # Novelty assessment
    mock_detection = {"is_candidate": True, "type": "Microlensing (Paczynski)"}
    assessment_known = matcher.assess_undocumented_bh_potential(res_bh, mock_detection)
    print("Documented object assessment:", assessment_known)
    assert assessment_known["undocumented_candidate"] is False, "Should not be marked as undocumented candidate if already in catalog"

    # Object not cataloged as a black hole (standard TIC star)
    res_star = {"is_known_object": True, "object_type": "TIC STAR", "is_documented_black_hole": False, "is_eclipsing_binary": False}
    assessment_new = matcher.assess_undocumented_bh_potential(res_star, mock_detection)
    print("Common star with anomalous signature assessment:", assessment_new)
    assert assessment_new["undocumented_candidate"] is True, "Should be cataloged as potential undocumented black hole candidate"

if __name__ == "__main__":
    test_microlensing_synthetic()
    test_ellipsoidal_synthetic()
    test_cross_match_mock()
    print("\n[OK] All tests passed successfully.")
